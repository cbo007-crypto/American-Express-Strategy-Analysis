American Express Company Strategy Analysis

Project Overview
This project evaluates the strategic position of American Express through an analysis of its business model, industry, competitors, and growth opportunities.

Project Objectives
- Analyse the financial services industry
- Evaluate American Express's competitive position
- Conduct a SWOT analysis
- Develop strategic recommendations
- Create an implementation roadmap

Tools Used
- Microsoft PowerPoint
- Microsoft Excel (supporting analysis)

Key Skills
- Strategic Analysis
- Business Strategy
- Competitive Benchmarking
- Executive Communication
- SWOT Analysis

Deliverables
- 12-slide executive presentation
- Strategic recommendations
- Implementation roadmap

Data Sources
- American Express Annual Report
- American Express Investor Relations
